#!/usr/bin/env node
// Generates the dashboard's PLACEHOLDER fixtures, deterministically, through T4's real buildAlert().
//   node sentinel/dashboard/fixtures/make-placeholders.mjs          (write files)
//   node sentinel/dashboard/fixtures/make-placeholders.mjs --check  (exit 1 if files are stale)
//
// Why placeholders exist: T3 (detector) and T7 (scoring) have not produced verdicts yet, so the alert
// feed has nothing real to show. Everything written here is labeled `placeholder: true` and the UI shows
// a PLACEHOLDER banner for it. These are NOT detector output.
//
// No new attack content is authored here. Every capture-specific value (tool-call ids, sink URLs,
// ledger actions, agent names) is read from the real T1 captures in captures/attack/ at generation
// time. The added bulk is benign: ordinary order rows, a plain travel-policy document, and a chain of
// neutral tool hops named step_1 … step_200.
//
// Outputs:
//   fixtures/alerts/attack__aim-ab.demo.alerts.json   runA verdict (sidecar for the real capture)
//   fixtures/alerts/attack__repo.demo.alerts.json     beat2 verdict
//   fixtures/alerts/attack__flight.demo.alerts.json   act2 verdict
//   fixtures/captures/data-rich-orders.json           600-row tool output + >8 KB doc around T1 runA
//   fixtures/captures/long-taint-path.json            200-hop taint path -> T4 truncation marker

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildAlert, BOUNDS as T4_BOUNDS } from '../../alerts/index.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..', '..');
const CAPTURES = path.join(REPO, 'captures');

export const DATA_RICH_ROWS = 600;
export const LONG_PATH_HOPS = 200;
const FIXED_TS = '2026-10-12T19:00:00.000Z';
const NOTE = 'PLACEHOLDER verdict generated by sentinel/dashboard/fixtures/make-placeholders.mjs through T4 buildAlert. Not detector output; replace with T3/T7 verdicts.';

const readJson = async (p) => JSON.parse(await readFile(p, 'utf8'));
const stripQuery = (u) => (u.includes('?') ? u.slice(0, u.indexOf('?')) : u);
const hostOf = (u) => new URL(u).host;

function alertFrom(verdict, warnings) {
  return buildAlert(
    { timestamp: FIXED_TS, state: 'new', ...verdict },
    { onWarning: (msg, detail) => warnings.push({ msg, detail }) },
  );
}

// ---- (a) sidecars for the real T1 attack captures ------------------------------------------------
function aimAbSidecar(cap, warnings) {
  const run = cap.runA;
  const tc = run.toolCalls[0];
  const dest = stripQuery(run.dvaa.exfilTargetUrl);
  const alert = alertFrom({
    alertId: 'placeholder-aim-ab-runA',
    category: 'taint_flow_exfil',
    ruleId: 'taint.untrusted_read_to_external_send',
    disposition: 'block',
    detectionLatencyMs: 2.4,
    entities: {
      agent: { name: 'RAGBot', id: 'dvaa-ragbot', port: 7005 },
      session: { id: 'aim-ab-runA' },
      toolCall: { id: tc.id, name: tc.function.name, argsPreview: JSON.stringify({ url: dest }) },
      sink: { type: 'http', destination: dest },
    },
    taintPath: [
      { kind: 'source', label: 'poisoned RAG document APWN-DE-003 (untrusted; rebuilt from DVAA template)', trust: 'untrusted' },
      { kind: 'sink', label: `${tc.function.name} → ${hostOf(dest)}`, toolCallId: tc.id, trust: 'external' },
    ],
    evidence: 'outbound call to a non-allowlisted local listener after reading an untrusted document',
    layers: [
      { layer: 'taint', rule: 'taint.untrusted_read_to_external_send', fired: true, latencyMs: 1.6 },
      { layer: 'egress', rule: 'egress.non_allowlisted_domain', fired: true, latencyMs: 0.8 },
    ],
  }, warnings);
  return { captureId: 'attack/aim-ab.demo', placeholder: true, note: NOTE, runs: { runA: [alert] } };
}

function repoSidecar(cap, warnings) {
  const ledger = cap.beat2.ledger;
  const idx = (pred) => ledger.findIndex(pred);
  const post = idx(l => /^http:post$/i.test(l.action));
  const reads = ledger.map((l, j) => [l, j]).filter(([l]) => /^fs:read$/i.test(l.action));
  if (post < 0) throw new Error('repo.demo beat2 has no http:post ledger entry; capture shape changed');
  const dest = stripQuery(ledger[post].target);
  const alert = alertFrom({
    alertId: 'placeholder-repo-beat2',
    category: 'taint_flow_exfil',
    ruleId: 'taint.untrusted_read_to_external_send',
    disposition: 'block',
    detectionLatencyMs: 3.1,
    entities: {
      agent: { name: cap.beat2.agent, id: 'dvaa-repobot', port: 7022 },
      session: { id: 'repo-beat2' },
      toolCall: { id: `beat2:ledger:${post}`, name: ledger[post].action, argsPreview: JSON.stringify({ url: dest }) },
      sink: { type: 'http', destination: dest },
    },
    taintPath: [
      { kind: 'source', label: 'repo-local config file (untrusted; body not recorded in T1 capture)', trust: 'untrusted' },
      ...reads.map(([l, j]) => ({ kind: 'propagate', label: `${l.action} ${l.target}`, toolCallId: `beat2:ledger:${j}`, trust: 'sensitive' })),
      { kind: 'sink', label: `${ledger[post].action} → ${hostOf(dest)}`, toolCallId: `beat2:ledger:${post}`, trust: 'external' },
    ],
    evidence: 'sensitive file reads followed by an outbound post in the same agent turn',
    layers: [
      { layer: 'taint', rule: 'taint.untrusted_read_to_external_send', fired: true, latencyMs: 2.2 },
      { layer: 'egress', rule: 'egress.non_allowlisted_domain', fired: true, latencyMs: 0.9 },
    ],
  }, warnings);
  return { captureId: 'attack/repo.demo', placeholder: true, note: NOTE, runs: { beat2: [alert] } };
}

